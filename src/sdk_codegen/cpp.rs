use std::{collections::BTreeMap, fmt::Write};

use super::plan::{Plan, count, enum_name, field_cpp, identifier, optional, scalar_cpp, type_name};
use crate::{
    codegen::{c_identifier, type_name as c_type_name},
    semantic::{FieldDefault, FieldSymbol, ResolvedType},
};

pub(super) fn emit(plan: &Plan<'_>, files: &mut BTreeMap<String, String>) {
    let name = &plan.options.name;
    // Keep system/Wirelink dependencies global, then isolate schema C typedefs
    // (e.g. Mode -> mode_t) from system typedefs in the C++ bridge.
    files.insert("src/native.hpp".into(), format!("/* SPDX-License-Identifier: Apache-2.0 */\n#pragma once\n#include <cfloat>\n#include <cstddef>\n#include <cstdint>\n#include <wirelink/codec.h>\n// Only passive values cross this namespace. Endpoint callbacks stay in C.\nnamespace {name}::wlc_native {{\n#include \"{name}_values.h\"\n}}\n"));
    let native = files.get_mut("src/native.hpp").unwrap();
    native.push_str("// C enum macros must not rewrite scoped C++ enum member names.\n");
    for enumeration in &plan.enums {
        for value in &enumeration.values {
            writeln!(
                native,
                "#undef {}",
                crate::codegen::upper_snake(&value.name)
            )
            .unwrap();
        }
    }
    let mut types = format!(
        "/* SPDX-License-Identifier: Apache-2.0 */\n// Generated by WLC. All fields own their data.\n#pragma once\n#include <array>\n#include <cstdint>\n#include <optional>\n#include <string>\n#include <vector>\n\nnamespace {name} {{\n"
    );
    for enumeration in &plan.enums {
        writeln!(
            types,
            "enum class {} : std::int32_t {{",
            type_name(&enumeration.name)
        )
        .unwrap();
        for value in &enumeration.values {
            writeln!(types, "  {} = {},", enum_name(&value.name), value.number).unwrap();
        }
        types.push_str("};\n\n");
    }
    for message in &plan.messages {
        writeln!(types, "struct {} {{", type_name(&message.name)).unwrap();
        for field in &message.fields {
            writeln!(
                types,
                "  {} {}{{}};",
                field_cpp(field),
                identifier(&field.name)
            )
            .unwrap();
        }
        for field in &message.fields {
            if field.default.is_some() {
                let f = identifier(&field.name);
                writeln!(
                    types,
                    "  {} {f}_or_default() const {{ return {f}.value_or({}); }}",
                    scalar_cpp(&field.ty),
                    default_cpp(field)
                )
                .unwrap();
            }
        }
        types.push_str("};\n\n");
    }
    writeln!(types, "}} // namespace {name}").unwrap();
    files.insert(format!("include/{name}/types.hpp"), types);

    let mut methods = String::new();
    for rpc in &plan.profile.rpc_services {
        writeln!(methods, "  wirelink::Result<{}> {}(const {}& request,\n      std::chrono::milliseconds timeout = std::chrono::seconds(1));",
            type_name(&rpc.response_name), identifier(&rpc.name), type_name(&rpc.request_name)).unwrap();
        writeln!(methods, "  wirelink::Result<wirelink::Operation<{}>> {}_async(const {}& request,\n      std::chrono::milliseconds timeout = std::chrono::seconds(1));",
            type_name(&rpc.response_name), identifier(&rpc.name), type_name(&rpc.request_name)).unwrap();
    }
    files.insert(format!("include/{name}/client.hpp"), format!("/* SPDX-License-Identifier: Apache-2.0 */\n// Generated by WLC.\n#pragma once\n#include <{name}/types.hpp>\n#include <wirelink/cpp/session.hpp>\n#include <chrono>\n#include <utility>\n\nnamespace {name} {{\nclass Client {{\npublic:\n  static wirelink::Result<Client> connect(const wirelink::UdpOptions& options);\n  Client(Client&&) noexcept = default;\n  Client& operator=(Client&&) noexcept = default;\n  Client(const Client&) = delete;\n  Client& operator=(const Client&) = delete;\n{methods}  void close() noexcept {{ session_.close(); }}\n  void notify() noexcept {{ session_.notify(); }}\n  wl_err_t last_error() const noexcept {{ return session_.last_error(); }}\n  bool is_open() const noexcept {{ return session_.is_open(); }}\n  std::uint16_t local_port() const noexcept {{ return session_.local_port(); }}\nprivate:\n  explicit Client(wirelink::Session session) : session_(std::move(session)) {{}}\n  wirelink::Session session_;\n}};\n}} // namespace {name}\n"));

    let mut values = format!(
        "/* SPDX-License-Identifier: Apache-2.0 */\n// Generator-private owned conversions; never installed as a public header.\n#pragma once\n#include <{name}/types.hpp>\n#include \"native.hpp\"\n#include <algorithm>\n#include <cstring>\n\nnamespace {name}::wlc_detail {{\n"
    );
    for message in &plan.messages {
        let ty = type_name(&message.name);
        let c = c_type_name(&message.name);
        writeln!(values, "inline bool to_c(const {ty}& input, wlc_native::{c}_value_t& output) {{\n  (void)input;\n  wlc_native::{c}_value_clear(&output);").unwrap();
        for field in &message.fields {
            let f = identifier(&field.name);
            let cf = c_identifier(&field.name);
            let expr = if optional(field) {
                format!("(*input.{f})")
            } else {
                format!("input.{f}")
            };
            let presence = if optional(field) {
                format!("input.{f}.has_value()")
            } else {
                "true".to_owned()
            };
            writeln!(
                values,
                "  output.has_{cf} = {presence};\n  if (output.has_{cf}) {{"
            )
            .unwrap();
            if count(field).is_some() {
                if matches!(field.ty, ResolvedType::Float32 | ResolvedType::Float64) {
                    writeln!(
                        values,
                        "    std::memcpy(output.{cf}, {expr}.data(), sizeof(output.{cf}));"
                    )
                    .unwrap();
                } else {
                    writeln!(
                        values,
                        "    std::copy({expr}.begin(), {expr}.end(), output.{cf});"
                    )
                    .unwrap();
                }
            } else {
                match &field.ty {
                    ResolvedType::String | ResolvedType::Bytes => {
                        writeln!(values, "    if ({expr}.size() > {}U) return false;\n    output.{cf}.length = {expr}.size();\n    std::copy({expr}.begin(), {expr}.end(), output.{cf}.data);", field.max_length.unwrap()).unwrap();
                    }
                    ResolvedType::Message { .. } => {
                        writeln!(values, "    if (!to_c({expr}, output.{cf})) return false;")
                            .unwrap();
                    }
                    ResolvedType::Enum { .. } => {
                        writeln!(
                            values,
                            "    output.{cf} = static_cast<std::int32_t>({expr});"
                        )
                        .unwrap();
                    }
                    ResolvedType::Float32 | ResolvedType::Float64 => {
                        writeln!(
                            values,
                            "    std::memcpy(&output.{cf}, &({expr}), sizeof(output.{cf}));"
                        )
                        .unwrap();
                    }
                    _ => {
                        writeln!(values, "    output.{cf} = {expr};").unwrap();
                    }
                }
            }
            values.push_str("  }\n");
        }
        writeln!(values, "  return true;\n}}\n\ninline {ty} from_c(const wlc_native::{c}_value_t& input) {{\n  (void)input;\n  {ty} output{{}};").unwrap();
        for field in &message.fields {
            let f = identifier(&field.name);
            let cf = c_identifier(&field.name);
            writeln!(values, "  if (input.has_{cf}) {{").unwrap();
            let dest = if optional(field) {
                writeln!(values, "    output.{f}.emplace();").unwrap();
                format!("(*output.{f})")
            } else {
                format!("output.{f}")
            };
            if let Some(n) = count(field) {
                if matches!(field.ty, ResolvedType::Float32 | ResolvedType::Float64) {
                    writeln!(
                        values,
                        "    std::memcpy({dest}.data(), input.{cf}, sizeof(input.{cf}));"
                    )
                    .unwrap();
                } else {
                    writeln!(values, "    std::copy_n(input.{cf}, {n}, {dest}.begin());").unwrap();
                }
            } else {
                match &field.ty {
                    ResolvedType::String | ResolvedType::Bytes => {
                        writeln!(values, "    {dest}.assign(input.{cf}.data, input.{cf}.data + input.{cf}.length);").unwrap();
                    }
                    ResolvedType::Message { .. } => {
                        writeln!(values, "    {dest} = from_c(input.{cf});").unwrap();
                    }
                    ResolvedType::Enum { .. } => {
                        writeln!(
                            values,
                            "    {dest} = static_cast<{}>(input.{cf});",
                            scalar_cpp(&field.ty)
                        )
                        .unwrap();
                    }
                    ResolvedType::Float32 | ResolvedType::Float64 => {
                        writeln!(
                            values,
                            "    std::memcpy(&({dest}), &input.{cf}, sizeof(input.{cf}));"
                        )
                        .unwrap();
                    }
                    _ => {
                        writeln!(values, "    {dest} = input.{cf};").unwrap();
                    }
                }
            }
            values.push_str("  }\n");
        }
        values.push_str("  return output;\n}\n\n");
    }
    writeln!(values, "}} // namespace {name}::wlc_detail").unwrap();
    files.insert("src/values.hpp".into(), values);

    let mut bridge_header = format!(
        r#"/* SPDX-License-Identifier: Apache-2.0 */
#pragma once
#include <stddef.h>
#include <wirelink/host/endpoint.h>
#ifdef __cplusplus
extern "C" {{
#endif
size_t {name}_sdk_endpoint_size(void);
size_t {name}_sdk_endpoint_alignment(void);
wl_err_t {name}_sdk_endpoint_prepare(void*, wl_host_endpoint_t*);
wl_err_t {name}_sdk_endpoint_initialize(void*, uint64_t, wl_packet_sink_fn, wl_packet_notify_fn, void*);
typedef struct {{
  void* endpoint;
  const void* request;
  void* response;
  wl_host_rpc_notify_fn notify;
  void* notify_context;
}} {name}_sdk_call_t;
"#
    );
    let mut bridge_source = format!(
        r#"/* SPDX-License-Identifier: Apache-2.0 */
/* C owns atomic port storage and all kernel callback types. */
#include "endpoint.h"
#include "{name}_kernel.h"
#include <string.h>
typedef struct {{
  {name}_kernel_t endpoint;
  wl_packet_port_t port;
  uint8_t rx[2][2053];
}} {name}_sdk_owner_t;
size_t {name}_sdk_endpoint_size(void) {{ return sizeof({name}_sdk_owner_t); }}
size_t {name}_sdk_endpoint_alignment(void) {{ return _Alignof({name}_sdk_owner_t); }}
wl_err_t {name}_sdk_endpoint_prepare(void* storage, wl_host_endpoint_t* descriptor) {{
  {name}_sdk_owner_t* owner = storage;
  memset(owner, 0, sizeof(*owner));
  *descriptor = (wl_host_endpoint_t){{owner, &owner->endpoint.core, &owner->port, 2052}};
  return WL_OK;
}}
wl_err_t {name}_sdk_endpoint_initialize(void* storage, uint64_t instance,
    wl_packet_sink_fn sink, wl_packet_notify_fn notify, void* user) {{
  {name}_sdk_owner_t* owner = storage;
  wl_packet_config_t config = {{.instance = instance, .rx_storage = &owner->rx[0][0],
    .rx_storage_size = sizeof(owner->rx), .rx_unit_size = sizeof(owner->rx[0]),
    .submit = sink, .notify = notify, .user = user}};
  const wl_err_t error = wl_packet_init(&owner->port, &config);
  if (error != WL_OK) return error;
  const {name}_kernel_handlers_t handlers = {{0}};
  return {name}_kernel_init(&owner->endpoint, &owner->port, &handlers, NULL, NULL);
}}
"#
    );
    for rpc in &plan.profile.rpc_services {
        let method = c_identifier(&rpc.name);
        let resp = c_type_name(&rpc.response_name);
        writeln!(bridge_header, "wl_err_t {name}_sdk_{method}_submit({name}_sdk_call_t*, uint32_t, uint32_t, wl_host_rpc_notify_fn, void*, wl_kernel_call_handle_t*);").unwrap();
        writeln!(bridge_source, r#"static void {name}_sdk_{method}_done(void* context, wl_kernel_result_t result, const {resp}_t* response) {{
  {name}_sdk_call_t* state = context;
  if (result.outcome == WL_KERNEL_SUCCESS &&
      (response == NULL || {resp}_value_from_view(response, state->response) != WL_CODEC_OK))
    result = (wl_kernel_result_t){{WL_KERNEL_LOCAL_ERROR, WL_ERR_CORRUPT_PAYLOAD}};
  state->notify(state->notify_context, result);
}}
wl_err_t {name}_sdk_{method}_submit({name}_sdk_call_t* state, uint32_t now, uint32_t timeout,
    wl_host_rpc_notify_fn notify, void* context, wl_kernel_call_handle_t* call) {{
  {name}_sdk_owner_t* owner = state->endpoint;
  state->notify = notify;
  state->notify_context = context;
  return {name}_kernel_{method}_start(&owner->endpoint, state->request, now, timeout,
      {name}_sdk_{method}_done, state, call);
}}
"#).unwrap();
    }
    bridge_header.push_str("#ifdef __cplusplus\n}\n#endif\n");
    files.insert("src/endpoint.h".into(), bridge_header);
    files.insert(
        "src/endpoint.c".into(),
        format!("{}\n", bridge_source.trim_end()),
    );
    let mut source = format!(
        r#"/* SPDX-License-Identifier: Apache-2.0 */
#include <{name}/client.hpp>
#include "values.hpp"
#include "endpoint.h"
#include <memory>
#include <new>
namespace {name} {{
using namespace wlc_native;
namespace {{
void destroy(void* pointer) noexcept {{
  ::operator delete(pointer, std::align_val_t({name}_sdk_endpoint_alignment()));
}}
void* create(wl_host_endpoint_t& descriptor, wirelink::Error& error) {{
  std::unique_ptr<void, decltype(&destroy)> storage(
      ::operator new({name}_sdk_endpoint_size(), std::align_val_t({name}_sdk_endpoint_alignment())), destroy);
  const auto status = {name}_sdk_endpoint_prepare(storage.get(), &descriptor);
  if (status != WL_OK) {{ error = wirelink::Error::local(status); return nullptr; }}
  return storage.release();
}}
}}
wirelink::Result<Client> Client::connect(const wirelink::UdpOptions& options) {{
  auto session = wirelink::Session::connect(options, {{create, {name}_sdk_endpoint_initialize, destroy}});
  if (!session) return session.error();
  return Client(std::move(session).value());
}}
"#
    );
    for rpc in &plan.profile.rpc_services {
        let method = identifier(&rpc.name);
        let c_method = c_identifier(&rpc.name);
        let req = type_name(&rpc.request_name);
        let resp = type_name(&rpc.response_name);
        let c_req = c_type_name(&rpc.request_name);
        let c_resp = c_type_name(&rpc.response_name);
        writeln!(source, r#"wirelink::Result<{resp}> Client::{method}(const {req}& request,
    std::chrono::milliseconds timeout) {{
  if (session_.on_owner_thread()) return wirelink::Error::local(WL_ERR_REENTRANT);
  auto operation = {method}_async(request, timeout);
  if (!operation) return operation.error();
  return operation.value().result();
}}
wirelink::Result<wirelink::Operation<{resp}>> Client::{method}_async(const {req}& request,
    std::chrono::milliseconds timeout) {{
  if (timeout.count() <= 0 || timeout.count() > INT32_MAX)
    return wirelink::Error::local(WL_ERR_INVALID_ARG);
  struct wlc_call_state final : wirelink::detail::OperationState<{resp}> {{
    {c_req}_value_t request{{}};
    {c_resp}_value_t response{{}};
    {name}_sdk_call_t bridge{{}};
    wl_err_t submit(uint32_t now, uint32_t timeout, wl_host_rpc_notify_fn notify, void* context,
        wl_kernel_call_handle_t* call) noexcept override {{
      bridge.endpoint = this->endpoint;
      bridge.request = &request;
      bridge.response = &response;
      return {name}_sdk_{c_method}_submit(&bridge, now, timeout, notify, context, call);
    }}
    {resp} decode_response() override {{ return wlc_detail::from_c(response); }}
  }};
  try {{
    auto call = std::make_shared<wlc_call_state>();
    if (!wlc_detail::to_c(request, call->request)) return wirelink::Error::local(WL_ERR_INVALID_ARG);
    const auto error = session_.submit(call, static_cast<uint32_t>(timeout.count()));
    if (error != WL_OK) return wirelink::Error::local(error);
    return wirelink::Operation<{resp}>(std::move(call));
  }} catch (const std::bad_alloc&) {{ return wirelink::Error::local(WL_ERR_NO_MEM); }}
}}
"#).unwrap();
    }
    writeln!(source, "}} // namespace {name}").unwrap();
    files.insert("src/client.cpp".into(), source);
}

fn default_cpp(field: &FieldSymbol) -> String {
    let (_, signed, unsigned, literal, _) = crate::codegen::field_descriptor_data(field);
    match field.default.as_ref().unwrap() {
        FieldDefault::String(s) => format!("std::string({literal}, {})", s.len()),
        FieldDefault::Bool(b) => b.to_string(),
        FieldDefault::Enum(n) => format!("static_cast<{}>({n})", scalar_cpp(&field.ty)),
        FieldDefault::Int64(i64::MIN) => "(-INT64_C(9223372036854775807) - 1)".into(),
        FieldDefault::Int64(_) => signed,
        FieldDefault::Int8(_) | FieldDefault::Int16(_) | FieldDefault::Int32(_) => signed,
        _ => format!("UINT64_C({unsigned})"),
    }
}
